// Parse the SEEDED_GAMES array
const startMarker = 'export const SEEDED_GAMES: GameItem[] = ';
const startIndex = code.indexOf(startMarker);
if (startIndex === -1) {
  console.error('Could not find startMarker in gamesCatalog.ts');
  process.exit(1);
}

const arrayCode = code.substring(startIndex + startMarker.length).trim();
const existingGames = eval(arrayCode);
console.log('Existing games count:', existingGames.length);

// Filter out existing Evolution games
const nonEvoGames = existingGames.filter(g => (g.provider || '').toLowerCase() !== 'evolution');
console.log('Non-Evolution games count:', nonEvoGames.length);

// Merge: put nonEvoGames and EVOLUTION_GAMES together
const updatedGames = [...nonEvoGames, ...EVOLUTION_GAMES];
console.log('Updated total games count:', updatedGames.length);
console.log('Evolution games added:', EVOLUTION_GAMES.length);

const newContent = `import type { GameItem } from '../src/types/index.ts';\n\nexport const SEEDED_GAMES: GameItem[] = ${JSON.stringify(updatedGames, null, 2)};\n`;

fs.writeFileSync(catalogPath, newContent, 'utf8');
